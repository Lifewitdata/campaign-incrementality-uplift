"""Phase 3 entrypoint: what a future campaign needs in order to be measurable.

    python scripts/run_power_analysis.py

Baselines are read from the control arm of the pinned dataset rather than typed
in, so the plan cannot drift from the data. Writes
``outputs/tables/power_analysis.csv``, ``outputs/tables/design_reality_check.csv``
and the generated ``reports/power_analysis.md``.
"""

from __future__ import annotations

from datetime import date

import pandas as pd

from campaign_ml.config import load_config, resolve
from campaign_ml.experimentation import CONTROL, arm_summary
from campaign_ml.power import (
    MONTE_CARLO_SIMULATIONS,
    assumptions_from_control,
    build_plan,
    realised_design_note,
)
from campaign_ml.validation import load_raw, prepare_clean_table


def main() -> int:
    config = load_config()
    exp = config["experiment"]
    df = prepare_clean_table(load_raw(resolve(config["data"]["raw_path"])))
    n_comparisons = len(exp["comparisons"])

    assumptions = assumptions_from_control(
        df, control_label=CONTROL, alpha=float(exp["alpha"]),
        power=0.80, n_comparisons=n_comparisons,
    )
    plan = pd.DataFrame(build_plan(assumptions))
    tables = resolve("outputs/tables")
    tables.mkdir(parents=True, exist_ok=True)
    plan.to_csv(tables / "power_analysis.csv", index=False)

    arm_sizes = arm_summary(df)[["arm", "n_customers"]]
    n_per_arm = int(arm_sizes["n_customers"].min())
    primary_treatment = exp["comparisons"][0]["treatment"]
    observed_rate = float(df.loc[df["segment"] == primary_treatment, "conversion"].mean())
    reality = pd.DataFrame([realised_design_note(n_per_arm, assumptions, observed_rate)])
    reality.to_csv(tables / "design_reality_check.csv", index=False)

    print(f"[assumptions] {assumptions.describe()}")
    for outcome in ["conversion", "spend"]:
        subset = plan[plan["outcome"] == outcome]
        print(f"[{outcome}] two-arm n per group from {subset['n_per_arm'].min():,.0f} "
              f"to {subset['n_per_arm'].max():,.0f}")
    print(f"[2008 design] {n_per_arm:,} per arm detected "
          f"{100 * reality['mde_conversion_absolute'][0]:.4f} pp conversion "
          f"({100 * reality['mde_conversion_relative'][0]:.1f}% relative) and "
          f"${reality['mde_spend_usd'][0]:.3f} per customer at 80% power")
    print(f"[2008 design] power for the observed {100 * observed_rate:.3f}% "
          f"{primary_treatment} conversion rate: "
          f"{100 * reality['achieved_power_at_observed_conversion_lift'][0]:.1f}%")

    observed = load_observed_effects()
    write_report(assumptions, plan, reality, n_per_arm, config, observed)
    return 0


def load_observed_effects() -> dict[str, float]:
    """Conversion lift already measured, so the report never hard-codes it."""
    path = resolve("outputs/tables/experiment_effects.csv")
    if not path.exists():
        raise FileNotFoundError(
            "run scripts/run_experiment_analysis.py before scripts/run_power_analysis.py"
        )
    effects = pd.read_csv(path)
    conversion = effects[(effects["outcome"] == "conversion")
                         & (effects["measure"] == "risk_difference")]
    return dict(zip(conversion["comparison"], conversion["effect"]))


def write_report(assumptions, plan: pd.DataFrame, reality: pd.DataFrame,
                 n_per_arm: int, config: dict, observed: dict[str, float]) -> None:
    """Generate the power report from the computed tables, never by hand."""
    alpha = float(config["experiment"]["alpha"])
    n_comparisons = len(config["experiment"]["comparisons"])
    conv = plan[(plan["outcome"] == "conversion")
                & (plan["alpha_convention"] == "per comparison")].reset_index(drop=True)
    conv_fwer = plan[(plan["outcome"] == "conversion")
                     & (plan["alpha_convention"] != "per comparison")].reset_index(drop=True)
    spend = plan[plan["outcome"] == "spend"].reset_index(drop=True)

    def conv_rows(frame: pd.DataFrame) -> str:
        return "\n".join(
            f"| {r['scenario']} | {100 * r['assumed_treatment_rate']:.3f}% | "
            f"{r['n_per_arm']:,.0f} | {r['n_total_three_arm']:,.0f} | "
            f"{100 * r['monte_carlo_power']:.1f}% |"
            for _, r in frame.iterrows()
        )

    md = f"""# Experiment planning: sample size and minimum detectable effect

Generated by `scripts/run_power_analysis.py` on {date.today().isoformat()}. Do not edit
the numbers by hand - they are recomputed from the pinned dataset.

## 1. Stated assumptions

{assumptions.describe()}

Baselines come from the **control arm** of the Hillstrom experiment (the customers who
received no email), because that is the state a future campaign is measured against.
Planning on the pooled rate would borrow treated customers' behaviour into the
"baseline" and make every send look easier to measure than it is.

| Quantity | Value | Where it comes from |
|---|---|---|
| Baseline conversion rate | {100 * assumptions.baseline_conversion:.4f}% | mean of `conversion` in `No E-Mail` |
| Baseline visit rate | {100 * assumptions.baseline_visit:.4f}% | mean of `visit` in `No E-Mail` |
| Spend SD (control) | ${assumptions.spend_sd:,.2f} | SD of `spend` in `No E-Mail`, zero-inflated and right-skewed |
| Spend mean (control) | ${assumptions.spend_mean:,.2f} | mean of `spend` in `No E-Mail` |
| Power target | {assumptions.power:.0%} | chosen for the plan, not observed |
| Comparisons against one control | {n_comparisons} | mens email, womens email |

Two-sided tests throughout. Where "family-wise" is written, alpha is split by
{alpha:.2f}/{n_comparisons} = {alpha / n_comparisons:.3f} (Bonferroni), which is the
conservative counterpart of the Holm adjustment used in the analysis.

## 2. Conversion: customers needed per arm

Assuming a {assumptions.baseline_conversion:.4%} control conversion rate and {assumptions.power:.0%} power.

| Desired lift | Implied treated rate | n per arm (alpha={alpha}) | n across all three arms | Monte-Carlo power |
|---|---|---|---|---|
{conv_rows(conv)}

The right-hand column is not the formula's own output repeated. It is the empirical
rejection rate of {MONTE_CARLO_SIMULATIONS:,} simulated experiments at exactly that sample
size, running the same pooled two-proportion z test the analysis uses. For a sub-1%
outcome the closed-form and simulated answers agree to around a percentage point, which is
the evidence that the normal approximation is earning its place here.

### The same question with family-wise error control

| Desired lift | Implied treated rate | n per arm (alpha={alpha / n_comparisons:.3f}) | n across all three arms | Monte-Carlo power |
|---|---|---|---|---|
{conv_rows(conv_fwer)}

Splitting alpha across the two email arms costs roughly a third more customers per arm.
That is the price of testing two campaigns against the same control and still being able
to say "family-wise 5%", and it should be quoted to whoever approves the send list.

## 3. Spending: customers needed per arm

Spend has a mean of ${assumptions.spend_mean:.3f} and a standard deviation of
${assumptions.spend_sd:,.2f} in the control arm - a coefficient of variation above 30,
driven by the fact that {100 * (1 - assumptions.baseline_conversion):.1f}% of customers spend
nothing. Sample size for a mean difference is therefore driven by the SD, not the mean.

| Detectable difference | n per arm (alpha={alpha}) | n across all three arms |
|---|---|---|
{chr(10).join(f"| ${r['scenario'].split('$')[1]} | {r['n_per_arm']:,.0f} | {r['n_total_three_arm']:,.0f} |" for _, r in spend[spend['alpha_convention'] == 'per comparison'].iterrows())}

## 4. What the 2008 design could actually detect

The published experiment randomised {n_per_arm:,} customers per arm.

| Question | Answer at 80% power |
|---|---|
| Smallest conversion lift detectable (absolute, family-wise alpha) | {100 * reality['mde_conversion_absolute'][0]:.4f} pp |
| Same, as a relative lift over the {100 * assumptions.baseline_conversion:.3f}% baseline | {100 * reality['mde_conversion_relative'][0]:.1f}% |
| Smallest visit lift detectable (absolute) | {100 * reality['mde_visit_absolute'][0]:.3f} pp |
| Smallest spend difference detectable | ${reality['mde_spend_usd'][0]:.3f} per customer |
| Power for the conversion rate the primary arm actually delivered | {100 * reality['achieved_power_at_observed_conversion_lift'][0]:.1f}% |

The mens email produced a {100 * observed['mens_vs_control']:.3f} pp conversion lift, well
above the detectable floor; the womens email produced {100 * observed['womens_vs_control']:.3f} pp,
which clears the same floor but with a correspondingly wider interval. That is why the two
arms get different-width confidence intervals in the incrementality dashboard, and why the
womens effect should be quoted with more caution - not because one result is nicer.

## 5. Recommendations for the next send

1. **Size to the decision, not to significance.** If the smallest lift worth acting on
   is a 20% relative conversion increase, the table above gives the required list size
   before the campaign starts.
2. **Keep a true no-email holdout, and size it deliberately.** The holdout is what makes
   these estimates causal; the incremental figures are only trustworthy while it exists.
3. **Budget for the multiplicity split.** Two creative variants against one control is two
   tests. Either pre-register one primary comparison or pay the sample-size cost shown in
   section 2.
4. **Do not plan a spend-powered test off the mean.** Plan off the SD, and treat the
   conversion estimate as the primary readout because it needs an order of magnitude
   fewer customers for the same precision.
5. **Hold back a random slice for uplift validation.** Uplift targeting claims made on the
   same customers who trained the model are not validated claims. See
   `reports/model_card.md`.

## 6. Limits of this analysis

- Assumed normality of the test statistic. At these sample sizes that is reasonable for
  proportions; the Monte-Carlo column checks it rather than asserting it.
- The spend figures use a Gaussian-theory interval on a skewed outcome, which is defensible
  at n in the tens of thousands and is exactly what the bootstrap cross-check in
  `experiment_effects.csv` confirms.
- One campaign, one retailer, one two-week window. Effects decay with send frequency and
  the 2008 email environment is not the current one; treat the baseline rates as the shape
  of the problem, not the numbers to reuse.
"""
    out = resolve("reports/power_analysis.md")
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(md, encoding="utf-8")
    print(f"[report] {out}")


if __name__ == "__main__":
    raise SystemExit(main())
